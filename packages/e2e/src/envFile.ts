import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ENV_FILE } from './composeArgs';

/** The fixed seed of the sample (NFR7.1); also written as a literal in compose.yaml. */
export const SEED = '20261106';

export type RandomSource = (bytes: number) => Buffer;

/** 32 hex characters from the system's secure random source (NFR5.2). */
export function generatePassword(random: RandomSource = randomBytes): string {
  return random(16).toString('hex');
}

export function parseEnvFile(text: string): Record<string, string> {
  const values: Record<string, string> = {};
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const index = trimmed.indexOf('=');
    if (index <= 0) continue;
    values[trimmed.slice(0, index).trim()] = trimmed.slice(index + 1).trim();
  }
  return values;
}

export interface EnsureEnvFileOptions {
  dir: string;
  random?: RandomSource;
  /** True when the PostgreSQL volume of the sample already exists. */
  volumeExists: () => boolean;
}

/**
 * Creates `.env.compose` when it is missing. Never overwrites, never prints
 * or returns the password, and refuses when the volume already holds a
 * database whose password a new file could not match.
 */
export function ensureEnvFile(options: EnsureEnvFileOptions): {
  created: boolean;
  path: string;
} {
  const path = join(options.dir, ENV_FILE);
  if (existsSync(path)) {
    return { created: false, path };
  }
  if (options.volumeExists()) {
    throw new Error(
      `${ENV_FILE} is missing but the database volume of the sample already exists, so a new password would not match it. Run "yarn compose:reset" to remove the volume (this deletes the sample data), then start again.`,
    );
  }
  const content = [
    '# Generated by yarn compose:up. Not committed; do not share.',
    'POSTGRES_HOST=postgres',
    'POSTGRES_PORT=5432',
    'POSTGRES_DB=guardrails',
    'POSTGRES_USER=guardrails',
    `POSTGRES_PASSWORD=${generatePassword(options.random)}`,
    '',
  ].join('\n');
  writeFileSync(path, content, { mode: 0o600, flag: 'wx' });
  return { created: true, path };
}

/** Stops when GUARDRAILS_SEED is anything but the fixed seed (NFR7.1). */
export function refuseOtherSeed(
  env: Record<string, string | undefined>,
  envFileText: string,
): void {
  const fromFile = parseEnvFile(envFileText).GUARDRAILS_SEED;
  for (const [where, value] of [
    ['the environment', env.GUARDRAILS_SEED],
    [ENV_FILE, fromFile],
  ] as const) {
    if (value !== undefined && value !== '' && value !== SEED) {
      throw new Error(
        `GUARDRAILS_SEED is set to another value in ${where}. The sample only runs with ${SEED}; remove GUARDRAILS_SEED and start again.`,
      );
    }
  }
}
